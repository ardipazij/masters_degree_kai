.include "m32def.inc"    ; Подключение файла с определениями для ATmega32
.device ATmega32         ; Указываем, что работаем с микроконтроллером ATmega32

; Сегмент данных (RAM)
.DSEG
table_fib:   .BYTE 10    ; Выделяем 10 байт для хранения чисел Фибоначчи
                          ; table_fib — метка (адрес первого элемента таблицы)

; Определение регистров
.DEF    fib1 = R1        ; (i-2)-е число Фибоначчи
.DEF    fib2 = R2        ; (i-1)-е число Фибоначчи
.DEF    fib  = R0        ; текущее i-е число Фибоначчи
.DEF    ind  = R16       ; счетчик/индекс для цикла

; Сегмент программы (код)
.CSEG
.ORG    0                ; Начало программы (адрес 0)

; Инициализация
main:   
        clr  fib1        ; fib1 = 0 (первое число Фибоначчи)
        clr  fib2        ; fib2 = 0
        inc  fib2        ; fib2 = 1 (второе число Фибоначчи)

        ; Настройка портов A, B, C как выходы
        ldi  r16, 0xFF   ; 0xFF = 11111111b
        out  DDRA, r16   ; порт A — выход
        ldi  r16, 0xFF
        out  DDRB, r16   ; порт B — выход
        ldi  r16, 0xFF
        out  DDRC, r16   ; порт C — выход

; Настройка указателя X на таблицу
        ldi  R26, low(table_fib)   ; младший байт адреса
        ldi  R27, high(table_fib)  ; старший байт адреса
        ; Регистр X = R27:R26 — используется для записи в RAM через st X+

; Запись первых двух чисел Фибоначчи в таблицу
        st   X+, fib1     ; table_fib[0] = fib1
        st   X+, fib2     ; table_fib[1] = fib2

        ldi  ind, 8       ; счетчик оставшихся чисел (всего 10, 2 уже записаны)

; Основной цикл вычисления чисел Фибоначчи
loop:   
        mov  fib, fib1    ; fib = fib1
        add  fib, fib2    ; fib = fib1 + fib2 (вычисление следующего числа Фибоначчи)
        st   X+, fib      ; сохраняем текущее число в таблицу table_fib

        ; Вывод текущих чисел на порты
        out  PORTA, fib1  ; вывод fib1 на порт A
        out  PORTB, fib2  ; вывод fib2 на порт B
        out  PORTC, fib   ; вывод текущего числа на порт C

        ; Сдвиг регистров для следующей итерации
        mov  fib1, fib2   ; fib1 = предыдущий fib2
        mov  fib2, fib    ; fib2 = текущее число fib

        dec  ind          ; уменьшаем счетчик
        brne loop         ; если счетчик != 0, повторяем цикл


; Конец программы

end:    
        rjmp end
